package repository

import (
	"context"
	"errors"

	"github.com/google/uuid"
	"github.com/joalberto902/tasks-api/internal/model"
)

// ErrNotFound is a sentinel error returned by some functions
// to point that the task does not exist in the repository
var ErrNotFound = errors.New("task not found")

// CreateTaskParams is a struct of the parameters necessary to
// create a new task
type CreateTaskParams struct {
	Title       string
	Status      model.TaskStatus
	Description string
}

// UpdateTaskParams is a struct of the optional parameters to
// update a task
type UpdateTaskParams struct {
	Title       *string
	Status      *model.TaskStatus
	Description *string
}

// TaskRepository is an interface that represents a repository or database
// of model.Tasks and the ways you should expect to interact with said repository
type TaskRepository interface {
	// Create creates a new task given the parameters, if it errors,
	// server side has failed.
	// ID, CreatedAt and UpdatedAt are automatically generated by the repository
	// Status is validated by the repository and defaults to StatusTodo if empty
	Create(ctx context.Context, arg CreateTaskParams) (model.Task, error)
	// List returns a slice with all Tasks, if it errors, server side has
	// failed
	List(ctx context.Context) ([]model.Task, error)
	// Get consumes an id and return the respective Tasks if it exists, else
	// ErrNotFound, others error means server side error
	Get(ctx context.Context, id uuid.UUID) (model.Task, error)
	// Update consumes an id and optional params to update partially the task
	// id may not exist and return ErrNotFound, else server side has
	// failed.
	// If arg.Title is nil, title does not change. For title is mandatory, then
	// a pointer to a empty string will error.
	// If arg.Status is nil, status does not change. If arg.Status is a pointer to
	// an empty string, then it defaults to StatusTodo.
	// If arg.Description is nil, description does not change. If arg.Description
	// is a pointer to an empty string, then the field is cleared.
	Update(ctx context.Context, id uuid.UUID, arg UpdateTaskParams) (model.Task, error)
	// Delete deletes a task given its id, if id does not exist in the repository it returns
	// ErrNotFound, else server side has failed.
	Delete(ctx context.Context, id uuid.UUID) error
}
